import assert from 'node:assert/strict';

export async function checkItemClassifications({ page, url, shot, checks }) {
    const choose = async (field, query, option) => { await field.fill(query); await page.getByRole('option', { name: option }).click(); };
    const row = (code) => page.locator('tbody tr').filter({ hasText: code });
    const ready = async () => page.waitForFunction(() => !document.querySelector('section[aria-busy="true"]'));
    const dialog = (name) => page.getByRole('dialog', { name, exact: true });
    await page.goto(`${url}/inventory/categories`);
    await page.keyboard.press('Control+Shift+n');
    await dialog('Tambah kategori').getByLabel('Kode', { exact: true }).fill('QA-CAT');
    await dialog('Tambah kategori').getByLabel('Nama', { exact: true }).fill('Kategori latihan');
    await page.keyboard.press('Control+Enter');
    await dialog('Tambah kategori').waitFor({ state: 'hidden' });
    await row('QA-CAT').getByRole('button', { name: 'Hapus Kategori latihan', exact: true }).click();
    await dialog('Hapus data?').getByRole('button', { name: 'Hapus', exact: true }).click();
    await dialog('Hapus data?').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Terhapus', exact: true }).click(); await ready();
    await row('QA-CAT').getByRole('button', { name: 'Pulihkan Kategori latihan', exact: true }).click();
    await dialog('Pulihkan data?').getByRole('button', { name: 'Pulihkan', exact: true }).click();
    await dialog('Pulihkan data?').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Data', exact: true }).click(); await ready();
    await row('QA-CAT').waitFor(); await shot('categories-desktop');
    await page.keyboard.press('F1');
    await page.getByRole('dialog').getByText('Panduan Kategori Barang', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    await page.goto(`${url}/inventory/brands`);
    await page.getByRole('button', { name: 'Tambah merek barang', exact: true }).click();
    await dialog('Tambah merek').getByLabel('Kode', { exact: true }).fill('QA-BRAND');
    await dialog('Tambah merek').getByLabel('Nama', { exact: true }).fill('Merek latihan');
    await dialog('Tambah merek').getByRole('button', { name: 'Simpan', exact: true }).click();
    await dialog('Tambah merek').waitFor({ state: 'hidden' });
    await page.goto(`${url}/inventory/items?search=DEMO-CCTV-IP-2MP`);
    await page.locator('tbody tr').getByRole('button', { name: /^Edit / }).click();
    const item = dialog('Edit barang');
    await choose(item.getByLabel('Kategori', { exact: true }), 'QA-CAT', /QA-CAT/);
    await choose(item.getByLabel('Merek', { exact: true }), 'QA-BRAND', /QA-BRAND/);
    await shot('item-classification-desktop');
    await item.getByRole('button', { name: 'Simpan', exact: true }).click(); await item.waitFor({ state: 'hidden' });
    await page.locator('tbody').getByText('Kategori latihan', { exact: true }).waitFor();
    await choose(page.getByLabel('Kategori', { exact: true }), 'QA-CAT', /QA-CAT/);
    await ready(); assert.equal(await page.locator('tbody tr').count(), 1);
    await page.setViewportSize({ width: 1024, height: 768 }); await shot('items-category-tablet');
    await page.goto(`${url}/inventory/categories`);
    await row('QA-CAT').getByRole('button', { name: 'Hapus Kategori latihan', exact: true }).click();
    await dialog('Hapus data?').getByRole('button', { name: 'Hapus', exact: true }).click();
    await dialog('Hapus data?').getByRole('alert').waitFor();
    assert.match(await dialog('Hapus data?').getByRole('alert').innerText(), /masih digunakan barang/);
    await dialog('Hapus data?').getByRole('button', { name: 'Batal', exact: true }).click();
    await page.goto(`${url}/pos`);
    await choose(page.getByRole('combobox', { name: 'Filter kategori POS', exact: true }), 'QA-CAT', /QA-CAT/);
    await choose(page.getByRole('combobox', { name: 'Filter merek POS', exact: true }), 'QA-BRAND', /QA-BRAND/);
    const catalog = page.getByRole('region', { name: 'Katalog barang', exact: true });
    await catalog.getByRole('button', { name: /^Tambah Kamera/ }).waitFor();
    assert.equal(await catalog.locator('article').count(), 1);
    await catalog.getByRole('button', { name: /^Tambah Kamera/ }).click();
    const cart = page.getByRole('region', { name: 'Keranjang', exact: true });
    await cart.getByRole('textbox', { name: /^Kuantitas / }).waitFor();
    await choose(page.getByRole('combobox', { name: 'Filter merek POS', exact: true }), 'Semua merek', 'Semua merek');
    await choose(page.getByRole('combobox', { name: 'Filter kategori POS', exact: true }), 'DEMO-ELECTRICAL', /DEMO-ELECTRICAL/);
    await catalog.getByRole('button', { name: /^Tambah MCB/ }).waitFor();
    assert.equal(await cart.getByRole('textbox', { name: /^Kuantitas / }).inputValue(), '1');
    assert((await page.getByTestId('catalog-scroll').boundingBox()).height > 180);
    await shot('pos-classifications-tablet');
    await page.getByLabel('Tampilan Klasik', { exact: true }).click();
    await shot('pos-classifications-classic-tablet');
    await page.getByLabel('Scan barcode', { exact: true }).fill('DEMO-CCTV-IP-2MP');
    await page.getByLabel('Scan barcode', { exact: true }).press('Enter');
    await page.waitForFunction(() => [...document.querySelectorAll('input')].some((input) => input.getAttribute('aria-label')?.startsWith('Kuantitas ') && input.value === '2'));
    await page.goto(`${url}/purchasing/purchase-orders`);
    await page.getByRole('button', { name: 'Tambah draft pembelian', exact: true }).click();
    const purchase = dialog('Tambah draft pembelian');
    await purchase.getByLabel('Catatan', { exact: true }).fill('Draft tetap utuh');
    await purchase.getByRole('button', { name: 'Tambah barang baris 1', exact: true }).click();
    const create = dialog('Tambah barang');
    await choose(create.getByLabel('Kategori', { exact: true }), 'QA-CAT', /QA-CAT/);
    await choose(create.getByLabel('Merek', { exact: true }), 'QA-BRAND', /QA-BRAND/);
    await create.getByRole('button', { name: 'Batal', exact: true }).click();
    assert.equal(await purchase.getByLabel('Catatan', { exact: true }).inputValue(), 'Draft tetap utuh');
    await purchase.getByRole('button', { name: 'Batal', exact: true }).click();
    checks.push('Category/brand CRUD, restore, used-reference guard, item assignments/price preservation, search filters, F1/shortcuts, desktop/tablet PASS');
    checks.push('POS visual/classic filters preserve cart; barcode ignores catalog filter; purchase quick-create choices/cancel preserve draft; stock/FIFO/payment/invoice fingerprints unchanged PASS');
}
