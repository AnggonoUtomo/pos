import assert from 'node:assert/strict';

export async function checkMasterAutocomplete({ page, url, shot, checks }) {
    const choose = async (field, query, option) => {
        await field.fill(query);
        await page.getByRole('option', { name: option }).click();
    };
    let purchasePosts = 0;
    page.on('request', (request) => {
        if (request.method() === 'POST' && new URL(request.url()).pathname === '/purchasing/purchase-orders') purchasePosts++;
    });
    await page.goto(`${url}/purchasing/purchase-orders`);
    await page.getByRole('button', { name: 'Tambah draft pembelian', exact: true }).click();
    const parent = page.getByRole('dialog', { name: 'Tambah draft pembelian', exact: true });
    await parent.getByLabel('Catatan', { exact: true }).fill('QA autocomplete draft');
    const warehouse = parent.getByLabel('Gudang', { exact: true });
    await choose(warehouse, 'WH-MAIN', /WH-MAIN/);
    const item = parent.getByLabel('Barang 1', { exact: true });
    await item.fill('zz-nonexistent');
    await page.getByText('Tidak ada pilihan yang cocok.', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert(await parent.isVisible(), 'Escape dropdown must not close purchase');
    await item.fill('DEMO-CCTV-IP-2MP');
    await page.getByRole('option', { name: /DEMO-CCTV-IP-2MP/ }).waitFor();
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
    assert.match(await item.inputValue(), /DEMO-CCTV-IP-2MP/);
    await parent.getByLabel('Kuantitas 1', { exact: true }).fill('2');
    await parent.getByLabel('Harga beli 1', { exact: true }).fill('120.000');
    await parent.getByRole('button', { name: 'Tambah supplier', exact: true }).click();
    let child = page.getByRole('dialog', { name: 'Tambah supplier', exact: true });
    await child.getByRole('button', { name: 'Batal', exact: true }).click();
    assert.equal(await parent.getByLabel('Catatan').inputValue(), 'QA autocomplete draft');
    await parent.getByRole('button', { name: 'Tambah supplier', exact: true }).click();
    await child.getByLabel('Kode', { exact: true }).fill('QA-AUTO-SUP');
    await child.getByLabel('Nama', { exact: true }).fill('Supplier Autocomplete QA');
    assert(await child.getByRole('checkbox', { name: 'Aktif', exact: true }).isDisabled());
    await child.getByRole('button', { name: 'Simpan', exact: true }).click();
    await child.waitFor({ state: 'hidden' });
    assert.match(await parent.getByLabel('Supplier', { exact: true }).inputValue(), /QA-AUTO-SUP/);
    await parent.getByRole('button', { name: 'Tambah barang baris 1', exact: true }).click();
    child = page.getByRole('dialog', { name: 'Tambah barang', exact: true });
    await child.getByLabel('SKU', { exact: true }).fill('QA-AUTO-ITEM');
    await child.getByLabel('Nama barang', { exact: true }).fill('Barang Autocomplete QA');
    const base = child.getByLabel('Satuan dasar', { exact: true });
    await base.fill('');
    const list = page.getByRole('listbox');
    await list.waitFor();
    assert.equal(await page.getByRole('option').count(), 100);
    assert(await list.evaluate((node) => node.scrollHeight > node.clientHeight));
    await list.hover(); await page.mouse.wheel(0, 300);
    await page.waitForFunction(() => document.querySelector('[role="listbox"]')?.scrollTop > 0);
    await choose(base, 'Unit', /^Unit \(unit\)$/);
    assert(await child.getByRole('combobox', { name: 'Satuan baris 1', exact: true }).isDisabled());
    for (const price of await child.getByRole('textbox', { name: /^Harga Unit / }).all()) await price.fill('200.000');
    assert((await child.getByRole('textbox', { name: /^Harga Unit / }).count()) >= 1);
    await shot('autocomplete-item-desktop');
    await child.getByRole('button', { name: 'Simpan', exact: true }).click();
    await child.waitFor({ state: 'hidden' });
    assert.match(await item.inputValue(), /QA-AUTO-ITEM/);
    assert.equal(await parent.getByLabel('Kuantitas 1', { exact: true }).inputValue(), '2');
    assert.equal(await parent.getByLabel('Harga beli 1', { exact: true }).inputValue(), '120.000');
    assert.equal(await parent.getByLabel('Catatan').inputValue(), 'QA autocomplete draft');
    assert.match(await warehouse.inputValue(), /WH-MAIN/);
    await page.setViewportSize({ width: 1024, height: 768 });
    await item.fill('Autocomplete');
    await page.getByRole('option', { name: /QA-AUTO-ITEM/ }).waitFor();
    await shot('autocomplete-purchase-tablet');
    await page.getByRole('option', { name: /QA-AUTO-ITEM/ }).click();
    await parent.getByRole('button', { name: 'Batal', exact: true }).click();
    assert.equal(purchasePosts, 0, 'Creating masters/cancel must never save or post a purchase');
    await page.getByRole('button', { name: 'Tambah draft pembelian', exact: true }).click();
    await choose(parent.getByLabel('Supplier', { exact: true }), 'QA-AUTO-SUP', /QA-AUTO-SUP/);
    await choose(parent.getByLabel('Barang 1', { exact: true }), 'QA-AUTO-ITEM', /QA-AUTO-ITEM/);
    await parent.getByRole('button', { name: 'Batal', exact: true }).click();
    await page.goto(`${url}/finance/payment-methods`);
    await page.locator('h1').waitFor();
    const account = page.getByLabel('Akun', { exact: true });
    await account.fill('Kas');
    await page.getByRole('option').first().click();
    await page.waitForFunction(() => document.querySelector('#payment-account-filter')?.value.includes('Kas'));
    await shot('autocomplete-finance-tablet');
    await page.goto(`${url}/inventory/stock`);
    await choose(page.getByRole('combobox', { name: 'Filter gudang', exact: true }), 'WH-MAIN', /WH-MAIN/);
    await page.getByRole('button', { name: 'Tambah stok awal', exact: true }).click();
    const opening = page.getByRole('dialog', { name: 'Tambah stok awal', exact: true });
    await choose(opening.getByLabel('Gudang', { exact: true }), 'WH-MAIN', /WH-MAIN/);
    await choose(opening.getByLabel('Barang 1', { exact: true }), 'QA-AUTO-ITEM', /QA-AUTO-ITEM/);
    await opening.getByRole('button', { name: 'Batal', exact: true }).click();
    await page.goto(`${url}/purchasing/purchase-orders`);
    await page.keyboard.press('F1');
    await page.getByRole('dialog').getByText('Mencari pilihan', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    checks.push('Autocomplete popup click/keyboard/empty/Escape, disabled base unit, supplier/item quick-create with complete prices, draft preservation, cancellation and reload of saved masters, desktop/tablet PASS');
    checks.push('Purchase, stock, FIFO and payment fingerprints unchanged; no accidental draft submit PASS');
}
